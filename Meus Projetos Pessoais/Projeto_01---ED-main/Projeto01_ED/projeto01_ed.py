import sys

class Node:
    def __init__(self, nome, idade, prioridade):
        self.nome = nome
        self.idade = idade
        self.prioridade = prioridade  # 1 = normal e 2 = prioritário
        self.prev = None
        self.next = None


class FilaDePacientes:
    def __init__(self):
        self.primeiro = None
        self.ultimo = None
        self.qtd_prioritarios = 0
        self.qtd_normais = 0
        self.ultimo_atendido_prioritario = False  # controle da alternância

    def adicionar_paciente(self, nome, idade, prioridade):
        novo = Node(nome, idade, prioridade)

        if self.primeiro is None:  # lista vazia
            self.primeiro = self.ultimo = novo
        else:
            if prioridade == 2:  # prioritário
                atual = self.primeiro
                # Vai inserir no final da lista de prioritarios
                while atual is not None and atual.prioridade == 2:
                    atual = atual.next
                if atual is None:  # caso todos sejam prioritários
                    self.ultimo.next = novo
                    novo.prev = self.ultimo
                    self.ultimo = novo
                else:  # faz q insira antes do primeiro normal
                    anterior = atual.prev
                    if anterior:
                        anterior.next = novo
                        novo.prev = anterior
                    else:
                        self.primeiro = novo
                    novo.next = atual
                    atual.prev = novo
            else:  # normal
                self.ultimo.next = novo
                novo.prev = self.ultimo
                self.ultimo = novo

        if prioridade == 2:
            self.qtd_prioritarios += 1
        else:
            self.qtd_normais += 1

      #REMOVER PACIENTES
    def remover_paciente(self):
            if self.primeiro is None:
                print("Fila vazia, nenhum paciente para remover.")
                return

            # Verifica proporção para decidir se vai alternar
            alternar = False
            if self.qtd_normais > 0:
                if self.qtd_prioritarios / self.qtd_normais >= 1/7:
                    alternar = True

            atual = self.primeiro

            if alternar and self.ultimo_atendido_prioritario:
                # procura um normal
                while atual and atual.prioridade != 1:
                    atual = atual.next
            # senão vai manter o primeiro

            if atual is None:
                atual = self.primeiro

            # remove o nó atual
            if atual.prev:
                atual.prev.next = atual.next
            else:
                self.primeiro = atual.next
            if atual.next:
                atual.next.prev = atual.prev
            else:
                self.ultimo = atual.prev

            # atualiza os contadores
            if atual.prioridade == 2:
                self.qtd_prioritarios -= 1
                self.ultimo_atendido_prioritario = True
            else:
                self.qtd_normais -= 1
                self.ultimo_atendido_prioritario = False

            # Mostra quem foi removido e o próximo
            print(f"Paciente atendido: {atual.nome} ({'Prioritário' if atual.prioridade == 2 else 'Normal'})")
            if self.primeiro:
                print(f"Próximo paciente: {self.primeiro.nome} ({'Prioritário' if self.primeiro.prioridade == 2 else 'Normal'})")
            else:
                print("Não há mais pacientes na fila.")

            return atual  # retorna o nó removido (se precisar usar)


    def alterar_dados(self, nome_antigo, novo_nome=None, nova_idade=None, nova_prioridade=None):
        atual = self.primeiro
        while atual:
            if atual.nome == nome_antigo:
                # alterar dados
                if novo_nome:
                    atual.nome = novo_nome
                if nova_idade:
                    atual.idade = nova_idade
                if nova_prioridade and nova_prioridade != atual.prioridade:
                    # remover da fila
                    if atual.prev:
                        atual.prev.next = atual.next
                    else:
                        self.primeiro = atual.next
                    if atual.next:
                        atual.next.prev = atual.prev
                    else:
                        self.ultimo = atual.prev

                    if atual.prioridade == 2:
                        self.qtd_prioritarios -= 1
                    else:
                        self.qtd_normais -= 1

                    # atualizar prioridade
                    atual.prioridade = nova_prioridade
                    atual.prev = atual.next = None

                    # reinserir na posição correta/ atualiza a posição
                    self.adicionar_paciente(atual.nome, atual.idade, atual.prioridade)
                print(f"Dados do paciente '{nome_antigo}' atualizados com sucesso.")
                return
            atual = atual.next
        print(f"Paciente '{nome_antigo}' não encontrado na fila.")

    def mostrar(self):
        atual = self.primeiro
        while atual:
            tipo = "Prioritário" if atual.prioridade == 2 else "Normal"
            print(f"{atual.nome} ({atual.idade} anos) - {tipo}", end=" <-> ")
            atual = atual.next
        print("None")

    def memoria_total(self):
        total = sys.getsizeof(self)
        atual = self.primeiro
        while atual:
            total += sys.getsizeof(atual)
            total += sys.getsizeof(atual.nome)
            total += sys.getsizeof(atual.idade)
            total += sys.getsizeof(atual.prioridade)
            total += sys.getsizeof(atual.prev)
            total += sys.getsizeof(atual.next)
            atual = atual.next
        return total

    def exibir_grafico(self):
        if self.primeiro is None:
            print("Fila vazia.")
            return
        atual = self.primeiro
        representacao = ""
        while atual:
            tipo = "(P)" if atual.prioridade == 2 else "(N)"
            representacao += f"[ {atual.nome} {tipo} ]"
            if atual.next:
                representacao += " --> "
            atual = atual.next
        print(representacao)

    def exibir_grafico_invertido(self):
        if self.ultimo is None:
            print("Fila vazia.")
